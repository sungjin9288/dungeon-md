// Generates src/data/portraitManifest.ts from the jpg files actually present in
// public/assets/monsters/. Run `npm run gen:portraits` after adding or removing
// a monster portrait. Keeping the load list to files that EXIST means no 404s
// on boot (production-safe) while staying drop-in friendly.
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'public', 'assets', 'monsters');

const ids = readdirSync(dir)
  .filter((f) => f.toLowerCase().endsWith('.jpg'))
  .map((f) => f.replace(/\.jpg$/i, ''))
  .sort();

const out = `// AUTO-GENERATED by scripts/gen-portrait-manifest.mjs — do not edit by hand.
// Monster ids that have an illustrated portrait at public/assets/monsters/{id}.jpg.
// Loaded as 'monster-ai-{id}' in BootScene; monsters not listed fall back to
// procedural PixelMonsters art. Regenerate with: npm run gen:portraits
export const PORTRAIT_IDS: readonly string[] = ${JSON.stringify(ids, null, 2)};
`;

writeFileSync(join(root, 'src', 'data', 'portraitManifest.ts'), out);
console.log(`portraitManifest.ts written — ${ids.length} portrait ids`);
