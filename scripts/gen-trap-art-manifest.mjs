// Generates src/data/trapArtManifest.ts from the PNGs actually present in
// public/assets/traps/ (npm run gen:trap-art). Listing only existing files keeps
// boot free of 404s; ids not listed keep their emoji (see src/ui/TrapIcon.ts).
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'public', 'assets', 'traps');
const ids = (existsSync(dir) ? readdirSync(dir) : [])
  .filter(f => f.endsWith('.png'))
  .map(f => f.replace(/\.png$/, ''))
  .sort();

writeFileSync(join(root, 'src', 'data', 'trapArtManifest.ts'), `// AUTO-GENERATED by scripts/gen-trap-art-manifest.mjs — do not edit by hand.
// Trap / affliction ids with an icon at public/assets/traps/{id}.png, loaded as
// 'trap-art-{id}' in BootScene. Regenerate with: npm run gen:trap-art
export const TRAP_ART_IDS: readonly string[] = ${JSON.stringify(ids, null, 2)};
`);
console.log(`trapArtManifest.ts written — ${ids.length} trap art ids`);
