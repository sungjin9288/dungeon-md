// ─── RLE helpers ─────────────────────────────────────────────────────────────

function r(v: number, n: number): number[] { return Array(n).fill(v); }
function row(...segs: number[]): number[] {
  const out: number[] = [];
  for (let i = 0; i < segs.length; i += 2) out.push(...r(segs[i], segs[i + 1]));
  while (out.length < 24) out.push(0);
  return out.slice(0, 24);
}

